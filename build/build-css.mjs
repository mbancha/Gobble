// Compiles build/tailwind.css and inlines the result into index.html, so the
// game is one self-contained file with no CDN and no build step for players.
//
//   node build/build-css.mjs           rebuild the <style> block in index.html
//   node build/build-css.mjs --check   exit 1 if that block is stale
//
// Run this after adding or removing any Tailwind class in index.html.
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';
import path from 'path';
import fs from 'fs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const htmlPath = path.join(root, 'index.html');
const bin = path.join(root, 'node_modules/.bin/tailwindcss');

const START = '<!-- tailwind:start (generated by build/build-css.mjs — do not edit by hand) -->';
const END = '<!-- tailwind:end -->';

const check = process.argv.includes('--check');

if (!fs.existsSync(bin)) {
  const msg = 'tailwindcss CLI not found — run: npm install';
  if (check) { console.log(`SKIP ${msg}`); process.exit(0); }
  console.error(msg);
  process.exit(1);
}

const html = fs.readFileSync(htmlPath, 'utf8');
const a = html.indexOf(START);
const b = html.indexOf(END);
if (a === -1 || b === -1 || b < a) {
  console.error(`markers not found in index.html — expected\n  ${START}\n  ${END}`);
  process.exit(1);
}

// Scan index.html *without* the generated block, so the compiler never reads
// its own output back in (see build/tailwind.css).
const scan = path.join(root, 'node_modules/.gobble-scan.html');
const tmp = path.join(root, 'node_modules/.gobble-out.css');
fs.writeFileSync(scan, html.slice(0, a) + html.slice(b + END.length));
execFileSync(bin, ['-i', path.join(here, 'tailwind.css'), '-o', tmp, '--minify'], { stdio: 'pipe' });
const css = fs.readFileSync(tmp, 'utf8').trim();
fs.rmSync(tmp, { force: true });
fs.rmSync(scan, { force: true });

const block = `${START}\n<style>${css}</style>\n${END}`;
const next = html.slice(0, a) + block + html.slice(b + END.length);

if (next === html) {
  console.log(`index.html already up to date (${(css.length / 1024).toFixed(1)} kB of CSS)`);
  process.exit(0);
}
if (check) {
  console.error('index.html is STALE: run `npm run build:css` and commit the result');
  process.exit(1);
}

fs.writeFileSync(htmlPath, next);
console.log(`inlined ${(css.length / 1024).toFixed(1)} kB of CSS into index.html`);
